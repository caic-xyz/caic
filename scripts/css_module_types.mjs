// Generates exact CSS Module export declarations and checks missing, stale, or orphaned output.
import { watch } from "node:fs";
import { glob, readFile, stat, unlink, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import typedCssModules from "typed-css-modules";

const { default: DtsCreator } = typedCssModules;
const help = `Usage: node scripts/css_module_types.mjs --source-path PATH [--write | --watch]

Check exact CSS Module declarations without changing files.
  --write        Generate declarations and remove orphaned output.
  --watch        Generate declarations whenever CSS files change.
  --source-path  Directory containing CSS Modules.
  -h, --help     Show this help.
`;

async function readOptional(path) {
  try {
    return await readFile(path, "utf8");
  } catch (error) {
    if (error.code === "ENOENT") return null;
    throw error;
  }
}

async function update(source, write) {
  // A fresh loader observes edits to composition dependencies in watch mode.
  const creator = new DtsCreator({ EOL: "\n" });
  const declarations = new Set();
  let changed = false;
  for await (const path of glob("**/*.module.css", { cwd: source })) {
    const css = resolve(source, path);
    const declaration = `${css}.d.ts`;
    declarations.add(declaration);
    const { tokens } = await creator.create(css);
    const properties = tokens.sort().map((name) => `  readonly ${JSON.stringify(name)}: string;`);
    const content = [
      "// Generated by scripts/css_module_types.mjs. DO NOT EDIT.",
      "declare const classes: {",
      ...properties,
      "};",
      "export default classes;",
      "",
    ].join("\n");
    if ((await readOptional(declaration)) === content) continue;
    changed = true;
    if (write) await writeFile(declaration, content);
    else process.stderr.write(`Stale or missing CSS types: ${declaration}\n`);
  }
  for await (const path of glob("**/*.module.css.d.ts", { cwd: source })) {
    const declaration = resolve(source, path);
    if (declarations.has(declaration)) continue;
    changed = true;
    if (write) await unlink(declaration);
    else process.stderr.write(`Orphaned CSS types: ${declaration}\n`);
  }
  return changed;
}

async function main() {
  const args = process.argv.slice(2);
  let source = null;
  let mode = "check";
  for (let index = 0; index < args.length; index++) {
    const arg = args[index];
    if (arg === "-h" || arg === "--help") {
      process.stdout.write(help);
      return;
    }
    if (arg === "--source-path" && args[index + 1] && !args[index + 1].startsWith("--")) {
      source = resolve(args[++index]);
    } else if ((arg === "--write" || arg === "--watch") && mode === "check") mode = arg.slice(2);
    else throw new Error(`Invalid argument: ${arg}\n${help}`);
  }
  if (!source) throw new Error(`Missing --source-path\n${help}`);
  // Reading the source directory also rejects a misspelled source path.
  if (!(await stat(source)).isDirectory()) throw new Error(`Not a directory: ${source}`);
  if (mode !== "watch") {
    if ((await update(source, mode === "write")) && mode === "check") process.exitCode = 1;
    return;
  }
  let pending = Promise.resolve();
  let debounce = null;
  // Subscribe before generating so edits during the initial pass are not lost.
  const watcher = watch(source, { recursive: true }, (_event, filename) => {
    if (!filename?.endsWith(".css")) return;
    clearTimeout(debounce);
    debounce = setTimeout(() => {
      pending = pending.then(() => update(source, true)).catch((error) => process.stderr.write(`${error.message}\n`));
    }, 50);
  });
  try {
    await update(source, true);
  } catch (error) {
    watcher.close();
    throw error;
  }
  process.stdout.write("Watching CSS Module types\n");
}

main().catch((error) => {
  process.stderr.write(`${error.message}\n`);
  process.exitCode = 1;
});
